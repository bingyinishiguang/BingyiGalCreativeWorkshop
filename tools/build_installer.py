#!/usr/bin/env python3
"""由 ui/brand.json 生成 Inno Setup 脚本 installer/setup.iss。"""
from __future__ import annotations

import sys as _sys_boot


for _stream in (_sys_boot.stdout, _sys_boot.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass


import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WV2_BOOTSTRAPPER = ROOT / "installer" / "redist" / "MicrosoftEdgeWebview2Setup.exe"
brand = json.loads((ROOT / "ui" / "brand.json").read_text(encoding="utf-8"))

app_name = brand.get("appName", "冰翼Gal创作工坊")
app_en = brand.get("appNameEn", "BingyiGalCreativeWorkshop")
version = brand.get("version", "1.0")
creator = brand.get("creator", "冰翼逆时光")

wiz = ROOT / "brand-assets" / "inno-wizard.bmp"
wiz_small = ROOT / "brand-assets" / "inno-wizard-small.bmp"
ico = ROOT / "ui" / "app.ico"
if not ico.is_file():
    ico = ROOT / "brand-assets" / "app.ico"


import sys as _sys

_with_assets = ""
_dist_override = ""
_output_dir = ""
_output_name = ""
_script_file = ""
_argv = _sys.argv[1:]
for _index, _item in enumerate(_argv):
    if _item == "--dist-dir" and _index + 1 < len(_argv):
        _dist_override = _argv[_index + 1]
    elif _item == "--output-dir" and _index + 1 < len(_argv):
        _output_dir = _argv[_index + 1]
    elif _item == "--output-name" and _index + 1 < len(_argv):
        _output_name = _argv[_index + 1]
    elif _item == "--script" and _index + 1 < len(_argv):
        _script_file = _argv[_index + 1]
    elif _item == "--with-assets" and _index + 1 < len(_argv):
        _with_assets = _argv[_index + 1]
    elif _item.startswith("--with-assets="):
        _with_assets = _item.split("=", 1)[1]

_assets_dir = None
if _with_assets:
    _assets_dir = (ROOT / _with_assets).resolve() if not Path(_with_assets).is_absolute() else Path(_with_assets).resolve()
    if not _assets_dir.is_dir():
        print(f"[error] --with-assets 指向的目录不存在：{_assets_dir}")
        raise SystemExit(1)
    print("=" * 68)
    print("  正在生成【内测版】安装包：会把packs一并内置。")
    print(f"  素材来源：{_assets_dir}")
    print("  [!] 这个安装包内含游戏原始素材（有版权），")
    print("    只能发给确定的内测者，绝不能公开上传/分发。")
    print("=" * 68)



dist_dir = Path(_dist_override).resolve() if _dist_override else ROOT / "dist" / app_en
if _dist_override and not (dist_dir / (app_en+".exe")).is_file():
    raise ValueError("指定冻结版目录中没有主程序")
if dist_dir.is_dir():
    forbidden=[p for name in ('tts_bundle','tts_acceleration','torch') for p in dist_dir.rglob(name) if p.is_dir()]
    if forbidden:raise ValueError('主软件包混入推理资源，禁止生成安装包：'+str(forbidden[0]))
if dist_dir.is_dir() and not _assets_dir:
    leaked = []
    if (dist_dir / "sprite-packs").exists():
        leaked.append("sprite-packs 目录")
    for pattern in ("*.pbd", "*.sinfo"):
        for leaked_file in dist_dir.rglob(pattern):
            leaked.append(str(leaked_file.relative_to(dist_dir)))
    if leaked:
        print("[error] 打包防回归检查失败：dist 产物中混入素材内容，禁止生成安装包。")
        print("[error] 发现以下内容：")
        for entry in sorted(set(leaked)):
            print(f"  - {entry}")
        raise SystemExit(1)

lines = [
    f"; Inno Setup script — {app_name}",
    "; Auto-generated by tools/build_installer.py. Do not edit by hand.",
    "",
    f'#define MyAppName "{app_name}"',
    f'#define MyAppVersion "{version}"',
    f'#define MyAppPublisher "{creator}"',
    f'#define MyAppExeName "{app_en}.exe"',
    "",
    "[Setup]",
    "AppId={{B1E9A2C3-7F4E-4A1B-9C2D-8E5F6A7B8C9D}}",
    "AppName={#MyAppName}",
    "AppVersion={#MyAppVersion}",
    "AppPublisher={#MyAppPublisher}",
    "DefaultDirName={autopf}\\{#MyAppName}",
    "DefaultGroupName={#MyAppName}",
    "DisableProgramGroupPage=yes",
    "DisableDirPage=no",
    "OutputDir=" + str(Path(_output_dir).resolve() if _output_dir else ROOT / "dist"),


    "OutputBaseFilename="+_output_name if _output_name else f"OutputBaseFilename={app_en}-Setup-{version}" + ("-内测版" if _assets_dir else ""),
    "Compression=lzma",
    "SolidCompression=yes",
    "WizardStyle=modern",
    "PrivilegesRequired=lowest",
    "UninstallDisplayIcon={app}\\{#MyAppExeName}",
]
if ico.exists():
    lines.append(f"SetupIconFile={ico}")
if wiz.exists():
    lines.append(f"WizardImageFile={wiz}")
if wiz_small.exists():
    lines.append(f"WizardSmallImageFile={wiz_small}")

lines += [
    "",
    "[Languages]",
    'Name: "chinesesimp"; MessagesFile: "compiler:Languages\\ChineseSimplified.isl"',
    "",
    "[Tasks]",
    'Name: "desktopicon"; Description: "{cm:CreateDesktopIcon}"; '
    'GroupDescription: "{cm:AdditionalIcons}"',
    "",
    "[Files]",
]
if _assets_dir is not None:
    lines.append(f'Source: "{_assets_dir}\\*"; DestDir: "{{app}}\\packs\\{_assets_dir.name}"; '
                 'Flags: ignoreversion recursesubdirs createallsubdirs')
lines += [
    f'Source: "{dist_dir}\\*"; DestDir: "{{app}}"; '
    "Flags: ignoreversion recursesubdirs createallsubdirs",
]


for _doc in ("LICENSE", "THIRD_PARTY_NOTICES.md", "README.md", "NOTICE"):
    lines.append(f'Source: "{ROOT / _doc}"; DestDir: "{{app}}"; '
                 "Flags: ignoreversion")

#生成 LICENSE.txt 副本，供 Windows 直接打开许可文件。
_license = ROOT / "LICENSE"
_license_txt = ROOT / "LICENSE.txt"
if _license.is_file():
    try:
        current = _license_txt.read_bytes() if _license_txt.is_file() else b""
        wanted = _license.read_bytes()
        if current != wanted:
            _license_txt.write_bytes(wanted)
            print("[ok] LICENSE.txt（由 LICENSE 同步，供 Windows 直接打开）")
    except OSError as _error:
        print(f"[warn] 没能生成 LICENSE.txt：{_error}")

if _license_txt.is_file():
    lines.append(f'Source: "{_license_txt}"; DestDir: "{{app}}"; '
                 "Flags: ignoreversion")
else:
    lines.append(f'Source: "{_license}"; DestDir: "{{app}}"; '
                 'DestName: "LICENSE.txt"; Flags: ignoreversion')

if WV2_BOOTSTRAPPER.exists():
    lines.append(
        f'Source: "{WV2_BOOTSTRAPPER}"; '
        'DestDir: "{tmp}"; Flags: deleteafterinstall'
    )
lines += [
    "",
    "[Icons]",
    'Name: "{group}\\{#MyAppName}"; Filename: "{app}\\{#MyAppExeName}"; WorkingDir: "{app}"',
    'Name: "{autodesktop}\\{#MyAppName}"; Filename: "{app}\\{#MyAppExeName}"; '
    'WorkingDir: "{app}"; Tasks: desktopicon',
    "",
    "[Run]",
    'Filename: "{app}\\{#MyAppExeName}"; Description: "{cm:LaunchProgram,{#MyAppName}}"; '
    'Flags: nowait postinstall skipifsilent; WorkingDir: "{app}"',
    "",
]


data_dir_name = brand.get("dataDirName", "冰翼Gal创作工坊")
if not data_dir_name or data_dir_name in ('.','..') or any(c in data_dir_name for c in '/\\:'):
    raise ValueError('用户数据目录名称必须是单个文件夹名')
lines += ["", "[Code]"]


if WV2_BOOTSTRAPPER.exists():
    lines += [
        "const",
        "  WV2_KEY_64 = 'SOFTWARE\\WOW6432Node\\Microsoft\\EdgeUpdate\\Clients\\{F3017226-FE2A-4295-8BDF-00C3A9A7E4C5}';",
        "  WV2_KEY_32 = 'SOFTWARE\\Microsoft\\EdgeUpdate\\Clients\\{F3017226-FE2A-4295-8BDF-00C3A9A7E4C5}';",
        "  WV2_KEY_CU = 'Software\\Microsoft\\EdgeUpdate\\Clients\\{F3017226-FE2A-4295-8BDF-00C3A9A7E4C5}';",
        "",
    ]

lines += [
    "function InitializeUninstall(): Boolean;",
    "var",
    "  dataDir: String;",
    "begin",
    "  Result := True;",
    "  if SuppressibleMsgBox('是否同时删除本地数据（Library、设置、packs等）？' + #13#10 + '选「否」将保留，方便重装后继续使用。',",
    "            mbConfirmation, MB_YESNO or MB_DEFBUTTON2, IDNO) = IDYES then",
    "  begin",
    f"    dataDir := ExpandConstant('{{userappdata}}\\{data_dir_name}');",
    "    DelTree(dataDir, True, True, True);",
    "  end;",
    "end;",
]

if WV2_BOOTSTRAPPER.exists():
    lines += [
        "function WebView2Installed(): Boolean;",
        "var",
        "  ver: String;",
        "begin",
        "  Result := False;",
        "  if RegQueryStringValue(HKLM, WV2_KEY_64, 'pv', ver) then",
        "    Result := (ver <> '') and (ver <> '0.0.0.0');",
        "  if (not Result) and RegQueryStringValue(HKCU, WV2_KEY_CU, 'pv', ver) then",
        "    Result := (ver <> '') and (ver <> '0.0.0.0');",
        "  if (not Result) and RegQueryStringValue(HKLM, WV2_KEY_32, 'pv', ver) then",
        "    Result := (ver <> '') and (ver <> '0.0.0.0');",
        "end;",
        "",
        "procedure CurStepChanged(CurStep: TSetupStep);",
        "var",
        "  ResultCode: Integer;",
        "begin",
        "  if CurStep = ssPostInstall then",
        "    if not WebView2Installed() then",
        "      Exec(ExpandConstant('{tmp}\\MicrosoftEdgeWebview2Setup.exe'),",
        "           '/silent /install', '', SW_HIDE, ewWaitUntilTerminated, ResultCode);",
        "end;",
    ]
else:
    print(
        "[warn] 未找到 WebView2 Bootstrapper"
        "（installer\\redist\\MicrosoftEdgeWebview2Setup.exe），"
        "安装包将不包含 WebView2 运行时自动安装"
    )

out = Path(_script_file).resolve() if _script_file else ROOT / "installer" / "setup.iss"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(lines), encoding="utf-8")
print(f"[ok] {out}")
