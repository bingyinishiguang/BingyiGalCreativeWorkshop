const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const e2e=require('./ui_e2e_helper.cjs');
(async()=>{
 const url=process.argv[2],root=path.resolve(process.argv[3]||'工作数据/config-workspace-validation');
 const input=JSON.parse(fs.readFileSync(path.join(root,'inputs.json'),'utf8')),ids=input.ids;
 const before=new Set(fs.readdirSync(input.config.draftDirectory));
 const browser=await e2e.chromium.launch({executablePath:e2e.requireBrowser(),headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1366,height:900}}),errors=[];
  page.on('pageerror',e=>errors.push(String(e)));page.on('dialog',d=>d.accept());
  await page.goto(url);await page.locator('#nav-tools').click();await page.locator('#open-roughcut').click();await page.locator('#column-open').click();
  await page.locator('#configuration-page').waitFor({state:'visible'});await page.locator('#cfg-new').click();
  const state=()=>page.evaluate(()=>window.configurationWorkspace.snapshot());
  const fill=async(id,value)=>{await page.locator(id).fill(String(value));await page.locator(id).press('Tab');};
  const add=async(purpose,id)=>{await page.locator(`[data-cfg-purpose="${purpose}"]`).click();await page.locator(`[data-cfg-asset="${id}"] [data-cfg-add]`).click();};
  const idle=()=>page.waitForFunction(()=>!document.getElementById('configuration-page').classList.contains('busy'));
  await fill('#cfg-name','真实空隙验收 '+Date.now());
  await add('main',ids.sequenceVideo);await fill('#cfg-start',0);await fill('#cfg-length',10);await page.locator('#cfg-range').click();
  await add('main',ids.sequenceVideo);await fill('#cfg-start',14);await fill('#cfg-length',10);await fill('#cfg-gap-before',4);await page.locator('#cfg-range').click();
  const initial=(await state()).config.sequence,first=initial[0].itemId,second=initial[1].itemId;
  assert.equal((await state()).episode.voices.length,0);
  assert.match(await page.locator('#cfg-time-label').textContent(),/24\.000/);
  const ruler=await page.locator('.cfg-ruler').boundingBox();
  await page.locator('.cfg-ruler').click({position:{x:12*32,y:8}});
  assert.equal(await page.locator('#cfg-preview-canvas video,#cfg-preview-canvas .cfg-base').count(),0,'ruler position inside the gap displays empty background');
  assert.match(await page.locator('#cfg-duration').textContent(),/12\.000/);
  const drag=await page.evaluateHandle(()=>new DataTransfer());
  await page.locator(`[data-type="main"][data-id="${second}"]`).dispatchEvent('dragstart',{dataTransfer:drag});
  await page.locator(`[data-type="main"][data-id="${first}"]`).dispatchEvent('drop',{dataTransfer:drag});
  assert.deepEqual((await state()).config.sequence.map(r=>r.itemId),[second,first]);
  assert.equal((await state()).config.sequence[0].gapBefore,4,'the gap belongs to its component');
  await page.locator('#cfg-undo').click();assert.deepEqual((await state()).config.sequence.map(r=>r.itemId),[first,second]);
  await add('voice',ids.voice);await page.locator('#cfg-check').click();await idle();
  assert.match(await page.locator('#cfg-status').textContent(),/超出/);
  await page.locator('#cfg-properties').click();await page.locator('#cfg-duration-policy').selectOption('timeline');
  await fill('#cfg-episode','时间轴空隙验收');await fill('#cfg-drafts',input.config.draftDirectory);
  await page.locator('#cfg-check').click();await idle();assert.match(await page.locator('#cfg-duration').textContent(),/24\.000/);
  await page.locator('#cfg-preview-play').click();await idle();
  await page.waitForFunction(()=>document.getElementById('cfg-duration').textContent.includes(' / 24.000'));
  await page.locator('#cfg-preview-stop').click();
  const stopped=await page.locator('#cfg-duration').textContent();await page.waitForTimeout(200);
  assert.equal(await page.locator('#cfg-duration').textContent(),stopped);
  assert.equal(await page.locator('#cfg-preview video').evaluate(v=>v.paused),true);
  await page.locator('#cfg-save').click();await idle();
  await page.locator('#cfg-build').click();await page.waitForSelector('#configuration-page',{state:'hidden',timeout:60000});
  const added=fs.readdirSync(input.config.draftDirectory).filter(v=>!before.has(v));assert.equal(added.length,1);
  const dir=path.join(input.config.draftDirectory,added[0]),story=JSON.parse(fs.readFileSync(path.join(dir,'bingyi-storyboard.json'),'utf8'));
  const draft=JSON.parse(fs.readFileSync(path.join(dir,'draft_content.json'),'utf8'));
  assert.equal(story.durationUs,24_000_000);assert.equal(draft.duration,24_000_000);
  assert.equal(story.scenes[1].blank,true);assert.equal(story.scenes[1].durationUs,4_000_000);
  assert.deepEqual(draft.tracks[0].segments.map(s=>[s.target_timerange.start,s.target_timerange.duration]),[[0,10_000_000],[14_000_000,10_000_000]]);
  await page.locator('.editor-segment.background[data-scene-index="1"]').click();
  await page.waitForFunction(()=>getComputedStyle(document.getElementById('cut-preview')).backgroundColor==='rgb(0, 0, 0)');
  assert.equal(await page.locator('#cut-preview video').count(),0);
  assert.deepEqual(errors,[]);
  await page.screenshot({path:path.join(root,'configuration-gap-generated.png'),fullPage:true});
  fs.writeFileSync(path.join(root,'configuration-gaps-report.json'),JSON.stringify({passed:true,draft:dir,durationUs:story.durationUs,gapUs:4_000_000,checks:['real component drag','gap follows component','default voice blocks','timeline extends','preview play stop','real export gap','generated blank preview']},null,2));
  console.log('configuration real timeline gaps passed');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
