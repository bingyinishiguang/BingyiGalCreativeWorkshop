const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const e2e=require('./ui_e2e_helper.cjs');
(async()=>{
 const url=process.argv[2],root=path.resolve(process.argv[3]||'工作数据/config-workspace-validation');
 const input=JSON.parse(fs.readFileSync(path.join(root,'inputs.json'),'utf8')),ids=input.ids;
 const drafts=input.config.draftDirectory,before=new Set(fs.readdirSync(drafts));
 const browser=await e2e.chromium.launch({executablePath:e2e.requireBrowser(),headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1366,height:900}});page.on('dialog',d=>d.accept());
  const errors=[];page.on('pageerror',error=>errors.push(String(error)));
  await page.goto(url);await page.locator('#nav-tools').click();await page.locator('#open-roughcut').click();
  await page.waitForFunction(()=>window.cutEditor);
  const original=await page.evaluate(()=>JSON.stringify(window.cutEditor.snapshot()));
  await page.locator('#column-open').click();await page.locator('#configuration-page').waitFor({state:'visible'});
  const snapshot=()=>page.evaluate(()=>window.configurationWorkspace.snapshot());
  const fill=async(selector,value)=>{await page.locator(selector).fill(String(value));await page.locator(selector).press('Tab');};
  const add=async(purpose,id)=>{await page.locator(`[data-cfg-purpose="${purpose}"]`).click();await page.locator(`[data-cfg-asset="${id}"] [data-cfg-add]`).click();};
  const waitIdle=()=>page.waitForFunction(()=>!document.getElementById('configuration-page').classList.contains('busy'));
  await page.locator('#cfg-new').click();await fill('#cfg-name','配置页行为验收 '+Date.now());
  assert.equal((await snapshot()).config.sequence.length,0);
  assert.match(await page.locator('#cfg-time-label').textContent(),/卡片宽度不代表时长/);
  await add('main',ids.sequenceVideo);await fill('#cfg-start',1);await fill('#cfg-length',8);
  await page.locator('#cfg-range').click();assert.match(await page.locator('#cfg-status').textContent(),/已确认/);
  assert.equal((await snapshot()).episode.voices.length,0);
  assert.equal(await page.locator('.cfg-ruler').count(),1,'confirmed material ranges provide a ruler before narration is bound');
  assert.match(await page.locator('#cfg-time-label').textContent(),/已排画面秒尺.*8\.000.*待本期校验/);
  await add('voice',ids.voice);await page.locator('#cfg-check').click();await waitIdle();
  assert.match(await page.locator('#cfg-status').textContent(),/还差|缺/);
  await page.locator('#cfg-fill-gap').click();await page.locator(`[data-cfg-asset="${ids.alternateImage}"] [data-cfg-add]`).click();
  assert.equal((await snapshot()).config.sequence.at(-1).timing,'remainder');
  await add('overlay',ids.badge);assert.equal((await snapshot()).config.overlays.length,1);
  await page.locator('#cfg-undo').click();assert.equal((await snapshot()).config.overlays.length,0);
  await page.locator('#cfg-redo').click();assert.equal((await snapshot()).config.overlays.length,1);
  //Drop a real video payload into the static overlay lane: must reject it.
  const transfer=await page.evaluateHandle(v=>{const data=new DataTransfer();data.setData('application/x-bingyi-asset',JSON.stringify(v));return data;},{id:ids.sequenceVideo,kind:'video'});
  await page.locator('[data-lane="overlay"]').dispatchEvent('drop',{dataTransfer:transfer});
  assert.equal((await snapshot()).config.overlays.length,1);assert.match(await page.locator('#cfg-status').textContent(),/仅支持静态图片/);
  await add('bgm',ids.bgm);assert.equal((await snapshot()).config.bgmVolume,1);
  await page.locator('#cfg-properties').click();await fill('#cfg-episode','配置页参与验收');
  await fill('#cfg-directory',input.episodeDirectory);await fill('#cfg-drafts',drafts);
  const episode=(await snapshot()).episode;
  await page.locator('#cfg-save').click();await waitIdle();assert.match(await page.locator('#cfg-status').textContent(),/配置已保存/);
  assert.deepEqual((await snapshot()).episode,episode);
  assert.equal(await page.evaluate(()=>JSON.stringify(window.cutEditor.snapshot())),original,'configuration editing must not mutate the current project');
  await page.locator('#cfg-check').click();await waitIdle();assert.match(await page.locator('#cfg-status').textContent(),/安排可生成/);
  await page.screenshot({path:path.join(root,'configuration-workspace-ready.png'),fullPage:true});
  const saved=(await snapshot()).config;
  await page.locator('#cfg-build').click();await page.waitForSelector('#configuration-page',{state:'hidden',timeout:60000});
  assert.match(await page.locator('#cut-status').textContent(),/已生成独立剪映草稿/);
  const additions=fs.readdirSync(drafts).filter(v=>!before.has(v));assert.equal(additions.length,1);
  const dir=path.join(drafts,additions[0]);
  const storyboard=JSON.parse(fs.readFileSync(path.join(dir,'bingyi-storyboard.json'),'utf8'));
  assert.equal(storyboard.generation.source.revision,saved.revision);
  assert.equal(storyboard.generation.effectiveConfig.bgmVolume,1);
  assert.equal(storyboard.generation.resolved.sequence[0].sourceStartUs,1000000);
  assert.equal(storyboard.generation.resolved.sequence[0].durationUs,8000000);
  assert.equal(storyboard.overlays.length,1);
  assert.ok(storyboard.durationUs>21000000&&storyboard.durationUs<23000000);
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(root,'configuration-workspace-report.json'),JSON.stringify({passed:true,draft:dir,preset:saved.id,revision:saved.revision,durationUs:storyboard.durationUs,checks:['independent project','video source range','inline gap fill','undo redo','illegal drop rejection','save preserves episode','real isolated export']},null,2));
  console.log('configuration workspace behavior passed');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
