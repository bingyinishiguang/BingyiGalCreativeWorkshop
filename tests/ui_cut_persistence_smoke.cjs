// Exercise real persistence with failed auxiliary refreshes in the isolated preview.
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),e2e=require('./ui_e2e_helper.cjs');
(async()=>{
  const browser=await e2e.chromium.launch({executablePath:e2e.requireBrowser(),headless:true});
  const page=await browser.newPage({viewport:{width:1366,height:900}}),errors=[];
  const out=process.argv[3];fs.mkdirSync(out,{recursive:true});
  let acceptDialogs=true;
  page.on('pageerror',error=>errors.push(error.message));page.on('dialog',dialog=>acceptDialogs?dialog.accept():dialog.dismiss());
  const status=()=>page.locator('#cut-status').textContent();
  try{
    await page.goto(process.argv[2]);await page.locator('#boot-overlay').waitFor({state:'hidden'});
    await page.locator('#nav-tools').click();await page.locator('#open-roughcut').click();
    await page.locator('#cut-save').click();assert.match(await status(),/先添加图片或视频/);
    assert.equal(await page.evaluate(()=>cutEditor.isDirty()),false);
    await page.locator('#cut-assets [data-add-asset]').first().click();
    await page.locator('#editor-add-text').click();await page.locator('#text-content').fill('保存反馈验证');await page.locator('#text-content').press('Tab');
    await page.route('**/api/roughcut/projects',route=>route.fulfill({status:503,json:{error:'模拟列表暂不可用'}}));
    await page.locator('#cut-save').click();
    await page.waitForFunction(()=>!cutEditor.isBusy()&&document.querySelector('#cut-status').textContent.includes('项目列表暂未刷新'));
    assert.match(await status(),/项目已保存/);assert.equal(await page.evaluate(()=>cutEditor.isDirty()),false);
    const saved=await page.evaluate(()=>structuredClone(cutEditor.snapshot()));assert(saved.id);
    await page.locator('#studio-project-settings').click();
    await page.locator('#cut-name').fill(saved.name+' · 输入中');
    assert.equal(await page.evaluate(()=>cutEditor.isDirty()),true);
    await page.waitForFunction(()=>document.querySelector('#studio-project-state').textContent.endsWith('未保存修改'));
    await page.locator('#cut-name').fill(saved.name);
    assert.equal(await page.evaluate(()=>cutEditor.isDirty()),false);
    await page.locator('#studio-project-close').click();
    const stored=await page.evaluate(async id=>cutEditor.api('/api/roughcut/project?id='+id),saved.id);
    assert.equal(stored.textClips[0].text,'保存反馈验证');
    await page.locator('#editor-undo').click();assert.notEqual(await page.evaluate(()=>cutEditor.snapshot().textClips[0]?.text),'保存反馈验证');
    await page.locator('#editor-redo').click();assert.equal(await page.evaluate(()=>cutEditor.snapshot().textClips[0].text),'保存反馈验证');
    await page.locator('#cut-export').click();
    await page.waitForFunction(()=>!cutEditor.isBusy()&&document.querySelector('#cut-status').textContent.includes('已生成'));
    assert.match(await status(),/项目列表暂未刷新/);assert(await page.locator('#cut-open-output').isVisible());
    assert.equal(await page.evaluate(()=>cutEditor.isDirty()),false);
    await page.unroute('**/api/roughcut/projects');
    await page.evaluate(()=>cutText.update(0,{text:'失败后必须保留的修改'}));
    const unsaved=await page.evaluate(()=>JSON.stringify(cutEditor.snapshot()));
    await page.route('**/api/roughcut/save',route=>route.fulfill({status:500,json:{error:'模拟保存失败'}}));
    await page.locator('#cut-save').click();await page.waitForFunction(()=>!cutEditor.isBusy()&&document.querySelector('#cut-status').textContent==='模拟保存失败');
    assert.equal(await page.evaluate(()=>JSON.stringify(cutEditor.snapshot())),unsaved);
    assert.equal(await page.evaluate(()=>cutEditor.isDirty()),true);assert(await page.locator('#cut-save').isEnabled());
    await page.locator('#editor-undo').click();assert.equal(await page.evaluate(()=>cutEditor.snapshot().textClips[0].text),'保存反馈验证');
    await page.unroute('**/api/roughcut/save');
    await page.locator('#cut-save').click();await page.waitForFunction(()=>!cutEditor.isBusy());
    assert.equal(await page.locator('#cut-projects').inputValue(),saved.id);
    await page.locator('#cut-export').click();await page.waitForFunction(()=>!cutEditor.isBusy()&&document.querySelector('#cut-status').textContent.includes('已生成'));
    assert(await page.locator('#cut-open-output').isVisible());
    const second=await page.evaluate(async()=>{const p=structuredClone(cutEditor.snapshot());delete p.id;p.name='另一份隔离项目';return cutEditor.api('/api/roughcut/save',p);});
    await page.locator('#cut-back').click();await page.locator('#open-roughcut').click();
    await page.locator('#studio-project-settings').click();
    await page.locator('#cut-name').fill(saved.name+' · 未保存名称');acceptDialogs=false;
    await page.locator('#cut-projects').selectOption(second.id);
    assert.equal(await page.evaluate(()=>cutEditor.snapshot().id),saved.id);
    assert.equal(await page.locator('#cut-projects').inputValue(),saved.id);
    assert(await page.locator('#cut-open-output').isVisible());acceptDialogs=true;
    await page.locator('#cut-projects').selectOption(second.id);
    await page.waitForFunction(id=>cutEditor.snapshot().id===id,second.id);await page.locator('#studio-project-close').click();
    assert(await page.locator('#cut-open-output').isHidden());
    assert.equal(await page.evaluate(()=>cutEditor.isDirty()),false);
    await page.locator('#studio-project-settings').click();
    await page.locator('#cut-name').fill(second.name+' · 临时名称');await page.locator('#cut-name').press('Tab');
    await page.locator('#cut-name').fill(second.name);await page.locator('#cut-name').press('Tab');
    await page.locator('#studio-project-close').click();
    await page.evaluate(()=>cutText.update(0,{text:'名称还原后的下一次编辑'}));
    await page.locator('#editor-undo').click();
    assert.equal(await page.evaluate(()=>cutEditor.snapshot().name),second.name);
    assert.equal(await page.evaluate(()=>cutEditor.snapshot().textClips[0].text),second.textClips[0].text);
    await page.screenshot({path:path.join(out,'persistence-success.png')});assert.deepEqual(errors,[]);
    console.log('PASS: empty guidance, persisted success despite refresh failure, export path, save failure retains edits, undo/redo, current project selection, clear previous output');
  }catch(error){await page.screenshot({path:path.join(out,'failure.png')});throw error;}
  finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
